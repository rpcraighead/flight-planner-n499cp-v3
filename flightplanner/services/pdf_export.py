from fpdf import FPDF
from datetime import datetime, timezone


def generate_navlog_pdf(data):
    """Generate a NavLog PDF from route/weather/W&B data."""
    pdf = FPDF(orientation='L', unit='mm', format='Letter')
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    route_data = data.get('route_data', {})
    weather_data = data.get('weather_data', {})
    wb_data = data.get('wb_data', {})
    aircraft = route_data.get('aircraft', {})
    segments = route_data.get('segments', [])
    totals = route_data.get('totals', {})
    cruise = route_data.get('cruise', {})
    climb = route_data.get('climb', {})

    # Header
    pdf.set_font('Helvetica', 'B', 16)
    pdf.cell(0, 10, 'VFR Navigation Log', ln=True, align='C')

    pdf.set_font('Helvetica', '', 9)
    now = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    pts = route_data.get('route_points', [])
    route_str = ' > '.join(p.get('identifier', '') for p in pts) if pts else 'N/A'

    pdf.cell(130, 5, f'Date: {now}', ln=False)
    pdf.cell(0, 5, f'Aircraft: {aircraft.get("tail_number", "N/A")} ({aircraft.get("type_model", "")})', ln=True)
    pdf.cell(130, 5, f'Route: {route_str}', ln=False)
    pdf.cell(0, 5, f'Altitude: {cruise.get("altitude", "")} ft  |  RPM: {cruise.get("rpm", "")}', ln=True)
    pdf.ln(3)

    # Segments table
    pdf.set_font('Helvetica', 'B', 8)
    col_widths = [25, 25, 22, 22, 22, 25, 22, 22, 22]
    headers = ['From', 'To', 'Dist (nm)', 'TC', 'WCA', 'MH', 'GS (kt)', 'Time (min)', 'Fuel (gal)']
    for i, h in enumerate(headers):
        pdf.cell(col_widths[i], 6, h, border=1, align='C')
    pdf.ln()

    pdf.set_font('Helvetica', '', 8)
    for seg in segments:
        vals = [
            seg.get('from', ''), seg.get('to', ''),
            str(seg.get('distance_nm', '')), f"{seg.get('true_course', 0):.0f}",
            f"{seg.get('wind_correction', 0):.0f}", f"{seg.get('magnetic_heading', 0):.0f}",
            f"{seg.get('ground_speed', 0):.0f}", f"{seg.get('time_minutes', 0):.0f}",
            str(seg.get('fuel_gallons', '')),
        ]
        for i, v in enumerate(vals):
            pdf.cell(col_widths[i], 5, v, border=1, align='C')
        pdf.ln()

    pdf.ln(3)

    # Totals
    pdf.set_font('Helvetica', 'B', 9)
    pdf.cell(60, 6, 'Flight Summary', ln=True)
    pdf.set_font('Helvetica', '', 9)

    summary = [
        ('Total Distance', f"{totals.get('distance_nm', 0)} nm"),
        ('Total Time', f"{totals.get('time_minutes', 0)} min"),
        ('TAS', f"{cruise.get('true_airspeed', 0)} kt"),
    ]
    for label, val in summary:
        pdf.cell(50, 5, f'{label}:', ln=False)
        pdf.cell(40, 5, val, ln=True)

    pdf.ln(2)

    # Fuel summary
    pdf.set_font('Helvetica', 'B', 9)
    pdf.cell(60, 6, 'Fuel Summary', ln=True)
    pdf.set_font('Helvetica', '', 9)

    fuel_items = [
        ('Taxi', f"{totals.get('taxi_fuel', 0)} gal"),
        ('Climb', f"{climb.get('fuel_gallons', 0)} gal"),
        ('Cruise', f"{totals.get('cruise_fuel', 0)} gal"),
        ('Reserve (45 min)', f"{totals.get('reserve_fuel', 0)} gal"),
        ('TOTAL', f"{totals.get('total_fuel', 0)} gal"),
    ]
    for label, val in fuel_items:
        style = 'B' if label == 'TOTAL' else ''
        pdf.set_font('Helvetica', style, 9)
        pdf.cell(50, 5, f'{label}:', ln=False)
        pdf.cell(40, 5, val, ln=True)

    # W&B if present
    if wb_data:
        pdf.ln(3)
        pdf.set_font('Helvetica', 'B', 9)
        pdf.cell(60, 6, 'Weight & Balance', ln=True)
        pdf.set_font('Helvetica', '', 9)
        wb_items = [
            ('Total Weight', f"{wb_data.get('total_weight', 0)} lbs"),
            ('Max Weight', f"{wb_data.get('max_weight', 0)} lbs"),
            ('CG', f"{wb_data.get('cg', 0)} in"),
            ('CG Limits', f"{wb_data.get('cg_forward_limit', 0)} - {wb_data.get('cg_aft_limit', 0)} in"),
            ('Status', 'WITHIN LIMITS' if wb_data.get('within_all_limits') else 'OUT OF LIMITS'),
        ]
        for label, val in wb_items:
            pdf.cell(50, 5, f'{label}:', ln=False)
            pdf.cell(40, 5, val, ln=True)

    # Weather summary
    briefing = weather_data.get('briefing', {})
    metars = briefing.get('metars', [])
    if metars:
        pdf.ln(3)
        pdf.set_font('Helvetica', 'B', 9)
        pdf.cell(60, 6, 'Weather', ln=True)
        pdf.set_font('Helvetica', '', 7)
        for m in metars:
            raw = m.get('rawOb', '')
            sim = ' (simulated)' if m.get('simulated') else ''
            pdf.cell(0, 4, f"{raw}{sim}", ln=True)

    # Footer
    pdf.ln(5)
    pdf.set_font('Helvetica', 'I', 7)
    pdf.cell(0, 4, f'Generated by CAP San Diego Sr. Sq. 57 Flight Planner v3 - {now}', align='C')

    return pdf.output()
